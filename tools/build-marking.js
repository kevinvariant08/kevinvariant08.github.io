#!/usr/bin/env node
/* Builds marking/library.js from the problem files in marking/problems/.
   Run from the repo folder:   node tools/build-marking.js
   Add --check to validate without writing anything. */
'use strict';
var fs = require('fs'), path = require('path');
var parseProblem = require('./marking-parse.js').parseProblem;

var root = path.join(__dirname, '..');
var dir = path.join(root, 'marking', 'problems');
var outFile = path.join(root, 'marking', 'library.js');
var checkOnly = process.argv.indexOf('--check') >= 0;

var files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(function (f) { return /\.md$/.test(f); }).sort() : [];
if (!files.length) { console.error('No problem files found in marking/problems/.'); process.exit(1); }

var problems = [], errors = [], warnings = [], ids = {};
files.forEach(function (f) {
  var rel = path.join('marking', 'problems', f);
  var res = parseProblem(fs.readFileSync(path.join(dir, f), 'utf8'), rel);
  errors = errors.concat(res.errors); warnings = warnings.concat(res.warnings);
  if (res.problem) {
    if (ids[res.problem.id]) errors.push(rel + ': id "' + res.problem.id + '" is already used by ' + ids[res.problem.id]);
    ids[res.problem.id] = rel; problems.push(res.problem);
  }
});

warnings.forEach(function (w) { console.log('note   ' + w); });
if (errors.length) {
  errors.forEach(function (e) { console.error('ERROR  ' + e); });
  console.error('\n' + errors.length + ' problem' + (errors.length > 1 ? 's' : '') + ' to fix. Nothing was written.');
  process.exit(1);
}

var reviewed = problems.filter(function (p) { return p.reviewed; }).length;
console.log(problems.length + ' problems read (' + reviewed + ' reviewed, ' + (problems.length - reviewed) + ' drafts).');
if (checkOnly) { console.log('Check only: marking/library.js was not changed.'); process.exit(0); }

problems.sort(function (a, b) { return (a.topic < b.topic ? -1 : a.topic > b.topic ? 1 : 0) || a.difficulty - b.difficulty || (a.id < b.id ? -1 : 1); });
var js = '/* Generated by tools/build-marking.js from marking/problems/*.md. Do not edit by hand: edit the .md files and run the tool again. */\n'
  + 'window.HU_MARKING=' + JSON.stringify({ built: new Date().toISOString().slice(0, 10), problems: problems }) + ';\n';
fs.writeFileSync(outFile, js);
console.log('Wrote marking/library.js (' + Math.round(js.length / 1024) + ' KB).');
